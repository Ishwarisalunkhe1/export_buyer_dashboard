"""Create a clearly-labelled sample product presentation PDF for demo outreach."""

from __future__ import annotations

from pathlib import Path

from config import SAMPLE_PDF_PATH

LINES = [
    "DEMO PRODUCT PRESENTATION",
    "Singing Bowls for International Buyers",
    "",
    "Prepared for buyer outreach workflow demonstration.",
    "Product: Singing bowls / home decor wellness products",
    "Supplier location: India",
    "Target market example: United States",
    "",
    "Suggested buyer types:",
    "- Importers and distributors",
    "- Wholesalers and retailers",
    "- Wellness stores and showrooms",
    "- Home decor stores and interior studios",
    "",
    "This is a sample PDF generated by the dashboard.",
    "Replace it with a real product catalogue before sending real emails.",
]


def _escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _minimal_pdf(path: Path) -> None:
    text_lines = []
    y = 760
    for line in LINES:
        text_lines.append(f"BT /F1 12 Tf 60 {y} Td ({_escape(line)}) Tj ET")
        y -= 22
    content = "\n".join(text_lines).encode("latin-1", "replace")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
    ]

    pdf = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for index, obj in enumerate(objects, start=1):
        offsets.append(len(pdf))
        pdf += f"{index} 0 obj\n".encode() + obj + b"\nendobj\n"

    xref_offset = len(pdf)
    pdf += f"xref\n0 {len(objects) + 1}\n".encode()
    pdf += b"0000000000 65535 f \n"
    for offset in offsets[1:]:
        pdf += f"{offset:010d} 00000 n \n".encode()
    pdf += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_offset}\n%%EOF\n"
    ).encode()
    path.write_bytes(pdf)


def ensure_sample_pdf() -> Path:
    if SAMPLE_PDF_PATH.exists():
        return SAMPLE_PDF_PATH
    SAMPLE_PDF_PATH.parent.mkdir(parents=True, exist_ok=True)
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.pdfgen import canvas

        pdf = canvas.Canvas(str(SAMPLE_PDF_PATH), pagesize=letter)
        pdf.setTitle("Demo Singing Bowls Product Presentation")
        y = 750
        for line in LINES:
            font = "Helvetica-Bold" if line in LINES[:2] else "Helvetica"
            pdf.setFont(font, 14 if font.endswith("Bold") else 11)
            pdf.drawString(60, y, line)
            y -= 22
        pdf.save()
    except Exception:
        _minimal_pdf(SAMPLE_PDF_PATH)
    return SAMPLE_PDF_PATH
